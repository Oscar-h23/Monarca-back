CREATE TABLE IF NOT EXISTS monarca.favoritos (
 id_usuario bigint NOT NULL REFERENCES monarca.usuarios(id_usuario) ON DELETE CASCADE,
 id_producto bigint NOT NULL REFERENCES monarca.productos(id_producto) ON DELETE CASCADE,
 creado timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(id_usuario,id_producto)
);
CREATE INDEX IF NOT EXISTS favoritos_producto_idx ON monarca.favoritos(id_producto);
CREATE TABLE IF NOT EXISTS monarca.favoritos_alertas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario bigint NOT NULL,id_producto bigint NOT NULL,
 id_variante bigint NOT NULL REFERENCES monarca.variantes_producto(id_variante) ON DELETE CASCADE,
 nombre text NOT NULL,talla text NOT NULL,color text NOT NULL,
 precio_anterior numeric(10,2) NOT NULL,precio_nuevo numeric(10,2) NOT NULL,
 creado timestamptz NOT NULL DEFAULT now(),leida boolean NOT NULL DEFAULT false,
 FOREIGN KEY(id_usuario,id_producto) REFERENCES monarca.favoritos(id_usuario,id_producto) ON DELETE CASCADE,
 CHECK(precio_nuevo>=0 AND precio_nuevo<precio_anterior)
);
CREATE INDEX IF NOT EXISTS favoritos_alertas_usuario_idx ON monarca.favoritos_alertas(id_usuario,creado DESC);
CREATE INDEX IF NOT EXISTS favoritos_alertas_producto_idx ON monarca.favoritos_alertas(id_usuario,id_producto);
CREATE INDEX IF NOT EXISTS favoritos_alertas_variante_idx ON monarca.favoritos_alertas(id_variante);
ALTER TABLE monarca.favoritos ENABLE ROW LEVEL SECURITY;
ALTER TABLE monarca.favoritos_alertas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON monarca.favoritos, monarca.favoritos_alertas FROM PUBLIC, anon, authenticated;
CREATE OR REPLACE FUNCTION monarca.notificar_rebaja_favorito() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
 IF NEW.precio < OLD.precio AND NEW.activo AND NEW.stock > 0 THEN
 INSERT INTO monarca.favoritos_alertas(id_usuario,id_producto,id_variante,nombre,talla,color,precio_anterior,precio_nuevo)
 SELECT f.id_usuario,NEW.id_producto,NEW.id_variante,p.nombre,NEW.talla,NEW.color,OLD.precio,NEW.precio
 FROM monarca.favoritos f JOIN monarca.productos p ON p.id_producto=f.id_producto
 WHERE f.id_producto=NEW.id_producto AND p.activo;
 END IF;
 RETURN NEW;
END;
$$;
REVOKE EXECUTE ON FUNCTION monarca.notificar_rebaja_favorito() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS favoritos_rebaja ON monarca.variantes_producto;
