CREATE TABLE IF NOT EXISTS monarca.ml_auto_config (
 id smallint PRIMARY KEY CHECK(id=1), habilitado boolean NOT NULL DEFAULT false,
 horas integer NOT NULL DEFAULT 168 CHECK(horas IN (12,24,72,168)),
 hora integer NOT NULL DEFAULT 3 CHECK(hora BETWEEN 0 AND 23),
 min_nuevos integer NOT NULL DEFAULT 10 CHECK(min_nuevos BETWEEN 1 AND 1000),
 proxima timestamptz, ocupado_hasta timestamptz, ultimo_total integer NOT NULL DEFAULT 0 CHECK(ultimo_total>=0)
);
INSERT INTO monarca.ml_auto_config(id) VALUES(1) ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS monarca.ml_auto_historial (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inicio timestamptz NOT NULL DEFAULT now(),fin timestamptz,
 estado text NOT NULL CHECK(estado IN ('EN_CURSO','COMPLETADO','OMITIDO','ERROR')),
 registros integer NOT NULL DEFAULT 0,nuevos integer NOT NULL DEFAULT 0,id_modelo bigint,detalle text NOT NULL DEFAULT ''
);
ALTER TABLE monarca.ml_auto_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE monarca.ml_auto_historial ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON monarca.ml_auto_config, monarca.ml_auto_historial FROM PUBLIC, anon, authenticated;
