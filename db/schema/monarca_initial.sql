-- MonarcaDB: PostgreSQL schema used by Spring Boot / Hibernate.
-- Tables reside in a private schema, not exposed by Supabase's default Data API.
create schema if not exists monarca;
revoke all on schema monarca from public;
revoke all on schema monarca from anon, authenticated;

create table if not exists monarca.roles (
 id_rol bigint generated by default as identity primary key,
 nombre varchar(30) not null unique,
 descripcion varchar(150),
 activo boolean not null default true
);

create table if not exists monarca.usuarios (
 id_usuario bigint generated by default as identity primary key,
 id_rol bigint not null references monarca.roles(id_rol),
 nombres varchar(100) not null,
 apellidos varchar(100) not null,
 correo varchar(150) not null,
 password_hash varchar(255) not null,
 telefono varchar(20),
 tipo_documento varchar(20),
 numero_documento varchar(20),
 activo boolean not null default true,
 fecha_creacion timestamptz not null default now(),
 fecha_actualizacion timestamptz not null default now()
);
create unique index if not exists ux_usuarios_correo_ci on monarca.usuarios (lower(correo));

create table if not exists monarca.categorias (
 id_categoria bigint generated by default as identity primary key,
 nombre varchar(100) not null unique,
 slug varchar(120) not null unique,
 descripcion varchar(300),
 activo boolean not null default true,
 fecha_creacion timestamptz not null default now()
);

create table if not exists monarca.productos (
 id_producto bigint generated by default as identity primary key,
 id_categoria bigint not null references monarca.categorias(id_categoria),
 nombre varchar(150) not null,
 slug varchar(180) not null unique,
 descripcion text,
 marca varchar(100) default 'Monarca',
 precio_base numeric(10,2) not null check (precio_base >= 0),
 activo boolean not null default true,
 destacado boolean not null default false,
 fecha_creacion timestamptz not null default now(),
 fecha_actualizacion timestamptz not null default now()
);

create table if not exists monarca.variantes_producto (
 id_variante bigint generated by default as identity primary key,
 id_producto bigint not null references monarca.productos(id_producto),
 sku varchar(80) not null unique,
 talla varchar(20) not null,
 color varchar(50) not null,
 color_hex varchar(10),
 precio numeric(10,2) not null check (precio >= 0),
 stock integer not null default 0 check (stock >= 0),
 stock_minimo integer not null default 0 check (stock_minimo >= 0),
 activo boolean not null default true,
 fecha_creacion timestamptz not null default now(),
 fecha_actualizacion timestamptz not null default now(),
 constraint uk_producto_variante unique (id_producto,talla,color)
);

create table if not exists monarca.imagenes_producto (
 id_imagen bigint generated by default as identity primary key,
 id_producto bigint not null references monarca.productos(id_producto),
 id_variante bigint references monarca.variantes_producto(id_variante),
 url text not null,
 texto_alternativo varchar(200),
 principal boolean not null default false,
 orden integer not null default 0,
 fecha_creacion timestamptz not null default now()
);

create table if not exists monarca.metodos_pago (
 id_metodo_pago bigint generated by default as identity primary key,
 codigo varchar(30) not null unique,
 nombre varchar(100) not null unique,
 descripcion varchar(250),
 requiere_comprobante boolean not null default false,
 activo boolean not null default true
);

create table if not exists monarca.pedidos (
 id_pedido bigint generated by default as identity primary key,
 codigo_pedido varchar(40) unique,
 id_usuario bigint not null references monarca.usuarios(id_usuario),
 estado varchar(30) not null default 'PENDIENTE_PAGO',
 subtotal numeric(10,2) not null check (subtotal >= 0),
 descuento numeric(10,2) not null default 0 check (descuento >= 0),
 costo_envio numeric(10,2) not null default 0 check (costo_envio >= 0),
 total numeric(10,2) not null check (total >= 0),
 observacion varchar(500),
 fecha_pedido timestamptz not null default now(),
 fecha_actualizacion timestamptz not null default now()
);

create table if not exists monarca.detalles_pedido (
 id_detalle bigint generated by default as identity primary key,
 id_pedido bigint not null references monarca.pedidos(id_pedido),
 id_variante bigint not null references monarca.variantes_producto(id_variante),
 cantidad integer not null check (cantidad > 0),
 precio_unitario numeric(10,2) not null check (precio_unitario >= 0),
 subtotal numeric(10,2) not null check (subtotal >= 0),
 nombre_producto varchar(150) not null,
 sku varchar(80) not null,
 talla varchar(20),
 color varchar(50)
);

create table if not exists monarca.pagos (
 id_pago bigint generated by default as identity primary key,
 id_pedido bigint not null references monarca.pedidos(id_pedido),
 id_metodo_pago bigint not null references monarca.metodos_pago(id_metodo_pago),
 monto numeric(10,2) not null check (monto >= 0),
 estado varchar(30) not null default 'PENDIENTE',
 numero_operacion varchar(100),
 comprobante_url text,
 proveedor_pago varchar(100),
 referencia_externa varchar(150),
 observacion varchar(300),
 fecha_creacion timestamptz not null default now(),
 fecha_pago timestamptz,
 fecha_confirmacion timestamptz
);

create index if not exists ix_productos_categoria on monarca.productos(id_categoria);
create index if not exists ix_variantes_producto on monarca.variantes_producto(id_producto);
create index if not exists ix_imagenes_producto on monarca.imagenes_producto(id_producto);
create index if not exists ix_pedidos_usuario on monarca.pedidos(id_usuario);
create index if not exists ix_detalles_pedido on monarca.detalles_pedido(id_pedido);
create index if not exists ix_pagos_pedido on monarca.pagos(id_pedido);

